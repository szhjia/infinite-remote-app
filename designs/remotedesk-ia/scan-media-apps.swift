// Refresh the design preview’s installation snapshot without opening any applications.
// Run: swift designs/remotedesk-ia/scan-media-apps.swift
import AppKit

let candidates = [
    ("qqmusic", "QQ 音乐", "com.tencent.QQMusicMac"),
    ("youku", "优酷", "com.youku.mac"),
    ("iqiyi", "爱奇艺", "com.iqiyi.player"),
    ("tencent", "腾讯视频", "com.tencent.tenvideo"),
    ("netease", "网易云音乐", "com.netease.163music"),
    ("bilibili", "哔哩哔哩", "com.bilibili.bilibiliPC"),
    ("music", "音乐", "com.apple.Music"),
    ("tv", "Apple TV", "com.apple.TV"),
    ("iina", "IINA", "com.colliderli.iina"),
    ("quicktime", "QuickTime Player", "com.apple.QuickTimePlayerX")
]
let folder = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
let assets = folder.appendingPathComponent("assets/media-launcher")
try FileManager.default.createDirectory(at: assets, withIntermediateDirectories: true)

func resolveApp(_ bundleID: String) -> URL? {
    if let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID),
       Bundle(url: url)?.bundleIdentifier == bundleID { return url }
    // LaunchServices can be unavailable inside a shell sandbox. Check standard app locations.
    let locations = [
        URL(fileURLWithPath: "/Applications"),
        URL(fileURLWithPath: "/System/Applications"),
        FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Applications")
    ]
    return locations.lazy.compactMap { location in
        (try? FileManager.default.contentsOfDirectory(at: location, includingPropertiesForKeys: nil))?
            .first { $0.pathExtension == "app" && Bundle(url: $0)?.bundleIdentifier == bundleID }
    }.first
}

var snapshot: [[Any]] = []
for (id, name, bundleID) in candidates {
    let url = resolveApp(bundleID)
    var file = id == "netease" ? "netease.ico" : "\(id).png"
    if let url {
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        let image = NSImage(size: NSSize(width: 128, height: 128), flipped: false) { rect in
            icon.draw(in: rect)
            return true
        }
        if let tiff = image.tiffRepresentation,
           let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            file = "\(id).png"
            let target = assets.appendingPathComponent(file)
            if !FileManager.default.fileExists(atPath: target.path) { try png.write(to: target, options: .atomic) }
        }
    }
    snapshot.append([id, name, bundleID, url != nil, file])
    print("\(name): \(url == nil ? "未检测到安装" : "已安装")")
}
let json = try JSONSerialization.data(withJSONObject: snapshot, options: [.prettyPrinted, .withoutEscapingSlashes])
var script = Data("// Generated by scan-media-apps.swift. No local paths are included.\nconst apps = ".utf8)
script.append(json)
script.append(Data(";\n".utf8))
try script.write(to: folder.appendingPathComponent("media-installation-snapshot.js"), options: .atomic)
